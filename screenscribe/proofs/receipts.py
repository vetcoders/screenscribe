"""Frozen receipt schema, atomic writer, and MATRIX.md renderer."""

from __future__ import annotations

import json
import os
import tempfile
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

SCHEMA = "screenscribe.proof-receipt.v1"
VERDICT_PROVEN = "PROVEN"
VERDICT_NOT_PROVEN = "NOT-PROVEN"
# An element that declares itself unimplemented (e.g. a tool stub returning
# ``{"unsupported": True}``). Not a failure of the harness or the wiring, so it
# must never be stamped PROVEN and must not fail the doctor exit code.
VERDICT_UNSUPPORTED = "UNSUPPORTED"


@dataclass(frozen=True)
class ProofReceipt:
    """In-memory receipt before JSON serialization."""

    element: str
    kind: str  # "provider" | "tool"
    request_essence: str
    response_essence: str
    duration_ms: int
    verdict: str  # PROVEN | NOT-PROVEN | UNSUPPORTED
    reason: str = ""
    key_state: str = "n/a"
    ts: str = field(default_factory=lambda: datetime.now(UTC).isoformat())

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema": SCHEMA,
            "element": self.element,
            "kind": self.kind,
            "ts": self.ts,
            "request_essence": self.request_essence,
            "response_essence": self.response_essence,
            "duration_ms": self.duration_ms,
            "verdict": self.verdict,
            "reason": self.reason,
            "key_state": self.key_state,
        }


def _private_dir(out_dir: Path) -> None:
    """Create ``out_dir`` owner-only; diagnostics may quote provider errors."""
    out_dir.mkdir(parents=True, exist_ok=True)
    try:  # no-op on Windows
        out_dir.chmod(0o700)
    except OSError:
        pass


def _write_private_text(dest: Path, text: str) -> None:
    """Write ``text`` with 0600 perms regardless of the process umask."""
    fd = os.open(dest, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write(text)
    try:  # tighten a pre-existing file too
        os.chmod(dest, 0o600)
    except OSError:
        pass


def _sanitize_filename(name: str) -> str:
    """Turn an element name into a safe filename fragment."""
    keep: set[str] = set("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-.")
    return "".join(c if c in keep else "_" for c in name) or "element"


def write_receipt(out_dir: Path, receipt: ProofReceipt) -> Path:
    """Atomically write one receipt JSON to ``out_dir``."""
    _private_dir(out_dir)
    dest = out_dir / f"{_sanitize_filename(receipt.element)}.receipt.json"
    fd, temp_name = tempfile.mkstemp(suffix=".json", prefix=".receipt-", dir=out_dir)
    try:
        with open(fd, "w", encoding="utf-8") as handle:
            json.dump(receipt.to_dict(), handle, indent=2, ensure_ascii=False)
            handle.flush()
        Path(temp_name).replace(dest)
    except BaseException:
        Path(temp_name).unlink(missing_ok=True)
        raise
    return dest


def _escape_md_cell(text: str) -> str:
    """Escape pipe characters so table rows stay intact."""
    return text.replace("|", "\\|")


def render_matrix(receipts: list[ProofReceipt], out_dir: Path) -> Path:
    """Write MATRIX.md summarizing every receipt (owner-only, like receipts)."""
    _private_dir(out_dir)
    dest = out_dir / "MATRIX.md"

    providers = sorted((r for r in receipts if r.kind == "provider"), key=lambda r: r.element)
    tools = sorted((r for r in receipts if r.kind == "tool"), key=lambda r: r.element)

    lines: list[str] = [
        "# Screenscribe Proof Matrix",
        "",
        "| element | kind | verdict | duration_ms | reason |",
        "|---|---|---|---|---|",
    ]
    for receipt in providers + tools:
        lines.append(
            f"| {_escape_md_cell(receipt.element)} | {receipt.kind} | {receipt.verdict} | "
            f"{receipt.duration_ms} | {_escape_md_cell(receipt.reason or '-')} |"
        )

    proven = sum(1 for r in receipts if r.verdict == VERDICT_PROVEN)
    unsupported = sum(1 for r in receipts if r.verdict == VERDICT_UNSUPPORTED)
    not_proven = sum(1 for r in receipts if r.verdict == VERDICT_NOT_PROVEN)
    lines += [
        "",
        f"**Totals:** {len(receipts)} elements, {proven} PROVEN, "
        f"{unsupported} UNSUPPORTED, {not_proven} NOT-PROVEN.",
        "",
        "_Generated by `screenscribe doctor`_",
    ]

    _write_private_text(dest, "\n".join(lines))
    return dest


def run_proof(out_dir: Path, *, json_mode: bool = False) -> list[ProofReceipt]:
    """Run all provider probes and tool roundtrips, write receipts + matrix."""
    from .providers import run_provider_probes
    from .tools import run_tool_probes

    provider_receipts = run_provider_probes()
    tool_receipts = run_tool_probes()
    receipts = provider_receipts + tool_receipts

    for receipt in receipts:
        write_receipt(out_dir, receipt)
    render_matrix(receipts, out_dir)

    if json_mode:
        summary = {
            "schema": "screenscribe.proof-summary.v1",
            "ts": datetime.now(UTC).isoformat(),
            "out_dir": str(out_dir),
            "total": len(receipts),
            "proven": sum(1 for r in receipts if r.verdict == VERDICT_PROVEN),
            "unsupported": sum(1 for r in receipts if r.verdict == VERDICT_UNSUPPORTED),
            "not_proven": sum(1 for r in receipts if r.verdict == VERDICT_NOT_PROVEN),
            "receipts": [r.to_dict() for r in receipts],
        }
        _write_private_text(
            out_dir / "summary.json", json.dumps(summary, indent=2, ensure_ascii=False)
        )

    return receipts
